#!/usr/bin/env python3
"""Render ai/profiles/policy.toml into the permission deny lists.

    python3 -B -I scripts/gen-policy.py            write the generated files
    python3 -B -I scripts/gen-policy.py --check    write nothing, exit 1 on drift

Writes `.permissions.deny` in ai/claude/settings.json (every other key is left
as it is) and ai/copilot/deny-tools.zsh. Stdlib only; needs Python 3.11 for
tomllib. Exit 0 ok, 1 drift, 2 bad policy or interpreter.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from typing import Any

HEADER = "Generated by scripts/gen-policy.py from ai/profiles/policy.toml. Do not edit."
POLICY = "ai/profiles/policy.toml"
SETTINGS = "ai/claude/settings.json"
COPILOT = "ai/copilot/deny-tools.zsh"


class PolicyError(Exception):
    pass


if sys.version_info >= (3, 11):
    import tomllib

    def _toml(path: str) -> dict[str, Any]:
        try:
            with open(path, "rb") as handle:
                return tomllib.load(handle)
        except (OSError, tomllib.TOMLDecodeError) as err:
            raise PolicyError(f"{path}: {err}") from err

else:

    def _toml(path: str) -> dict[str, Any]:
        raise PolicyError("needs Python 3.11+ (tomllib)")


def load(path: str) -> dict[str, Any]:
    policy = _toml(path)
    validate(policy)
    return policy


TOP_KEYS = {"readers", "setup_shells", "command", "secret", "read", "raw"}
TABLE_KEYS = {
    "command": {"run", "flags", "targets", "copilot", "why"},
    "secret": {"path"},
    "read": {"glob"},
    "raw": {"rule"},
}


def _strings(value: Any, label: str) -> list[str]:
    if not isinstance(value, list) or not all(
        isinstance(item, str) and item for item in value
    ):
        raise PolicyError(f"{label}: must be a list of non-empty strings")
    return value


def validate(policy: dict[str, Any]) -> None:
    for key in policy:
        if key not in TOP_KEYS:
            raise PolicyError(f"unknown key {key!r}")
    _strings(policy.get("readers", []), "readers")
    _strings(policy.get("setup_shells", []), "setup_shells")
    for table, keys in TABLE_KEYS.items():
        entries = policy.get(table, [])
        if not isinstance(entries, list) or not all(
            isinstance(entry, dict) for entry in entries
        ):
            raise PolicyError(f"[[{table}]]: must be an array of tables")
        for entry in entries:
            for key, value in entry.items():
                if key not in keys:
                    raise PolicyError(f"[[{table}]]: unknown key {key!r}")
                if key in ("flags", "targets"):
                    _strings(value, f"[[{table}]] {key}")
                elif not isinstance(value, str) or not value.strip():
                    raise PolicyError(f"[[{table}]]: {key} must be a non-empty string")
    for cmd in policy.get("command", []):
        run = cmd.get("run")
        if run is None:
            raise PolicyError("[[command]] without a run")
        if "why" not in cmd:
            raise PolicyError(f"[[command]] {run!r}: missing why")
        if cmd.get("targets") and not cmd.get("flags"):
            raise PolicyError(f"[[command]] {run!r}: targets need flags")
        if "'" in cmd.get("copilot", ""):
            raise PolicyError(f"[[command]] {run!r}: bad copilot spec")
    for table, field in (("secret", "path"), ("read", "glob"), ("raw", "rule")):
        for entry in policy.get(table, []):
            if field not in entry:
                raise PolicyError(f"[[{table}]] without a {field}")


def command_rules(cmd: dict[str, Any]) -> list[str]:
    run: str = cmd["run"]
    flags: list[str] = cmd.get("flags", [])
    targets: list[str] = cmd.get("targets", [])
    if not flags:
        return [f"Bash({run})", f"Bash({run} *)"]
    out: list[str] = []
    for flag in flags:
        if not targets:
            out += [f"Bash({run} {flag}*)", f"Bash({run} * {flag}*)"]
            continue
        for target in targets:
            out += [
                f"Bash({run} {flag} {target})",
                f"Bash({run} * {flag} {target})",
                f"Bash({run} {flag} * {target})",
                f"Bash({run} * {flag} * {target})",
            ]
    return out


def one_star(rule: str) -> str:
    if rule.startswith("Bash("):
        return re.sub(r"\*+", "*", rule)
    return rule


def render_claude(policy: dict[str, Any], modules: list[str]) -> list[str]:
    rules: list[str] = []
    for cmd in policy.get("command", []):
        rules += command_rules(cmd)
    readers: list[str] = policy.get("readers", [])
    for secret in policy.get("secret", []):
        path: str = secret["path"]
        name = path[2:] if path.startswith("~/") else path
        rules.append(f"Read({path})")
        rules += [f"Bash({reader} */{name}*)" for reader in readers]
    rules += [f"Read({read['glob']})" for read in policy.get("read", [])]
    rules += [raw["rule"] for raw in policy.get("raw", [])]
    for shell in policy.get("setup_shells", []):
        rules.append(f"Bash({shell} *setup.sh*)")
    rules += ["Bash(./setup.sh*)", "Bash(./*/setup.sh*)"]
    rules += [f"Bash({module}/setup.sh*)" for module in modules]
    seen: set[str] = set()
    out: list[str] = []
    for rule in map(one_star, rules):
        if rule not in seen:
            seen.add(rule)
            out.append(rule)
    return out


def render_copilot(policy: dict[str, Any]) -> str:
    specs: list[str] = []
    for cmd in policy.get("command", []):
        spec = cmd.get("copilot")
        if spec and spec not in specs:
            specs.append(spec)
    lines = [f"# {HEADER}", "function copilot {", "  command copilot \\"]
    lines += [f"    --deny-tool='{spec}' \\" for spec in specs]
    lines += ['    "$@"', "}"]
    return "\n".join(lines) + "\n"


def _split(rule: str) -> tuple[str, str] | None:
    if "(" not in rule or not rule.endswith(")"):
        return None
    tool, inner = rule.split("(", 1)
    return tool, inner[:-1]


def _anchor(path: str) -> tuple[str, str]:
    """Split a Read path into (anchor, rest): home, absolute, settings, cwd."""
    if path.startswith("~/"):
        return "home", path[2:]
    if path.startswith("//"):
        return "absolute", path[2:]
    if path.startswith("/"):
        return "settings", path[1:]
    return "cwd", path[2:] if path.startswith("./") else path


def covers(pattern: str, rule: str) -> bool:
    """True when `pattern` matches the text of `rule`.

    Bash: `*` is any run of characters. Other tools use path globs: the
    anchors (`~/`, `//`, `/`, cwd) must agree, then `**` is any run and `*`
    stays within one path segment.
    """
    pat, target = _split(pattern), _split(rule)
    if pat is None or target is None or pat[0] != target[0]:
        return False
    if pat[0] == "Bash":
        stars = {"*": ".*", "**": ".*", "**/": ".*/"}
        glob, text = pat[1], target[1]
    else:
        stars = {"**/": "(?:.*/)?", "**": ".*", "*": "[^/]*"}
        (pat_anchor, glob), (rule_anchor, text) = _anchor(pat[1]), _anchor(target[1])
        if pat_anchor != rule_anchor:
            return False
    regex = "".join(
        stars.get(tok, re.escape(tok)) for tok in re.split(r"(\*\*/|\*\*|\*)", glob)
    )
    return re.fullmatch(regex, text) is not None


def discover_modules(root: str) -> list[str]:
    return sorted(
        name
        for name in os.listdir(root)
        if not name.startswith(".")
        and os.path.isfile(os.path.join(root, name, "setup.sh"))
    )


def render_settings(text: str, deny: list[str]) -> str:
    data = json.loads(text)
    data.setdefault("permissions", {})["deny"] = deny
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def _read(path: str) -> str | None:
    try:
        with open(path, encoding="utf-8") as handle:
            return handle.read()
    except FileNotFoundError:
        return None


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(prog="gen-policy", description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 on drift")
    parser.add_argument(
        "--root",
        default=os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
    )
    args = parser.parse_args(argv)

    try:
        policy = load(os.path.join(args.root, POLICY))
        deny = render_claude(policy, discover_modules(args.root))
        current = _read(os.path.join(args.root, SETTINGS))
        if current is None:
            raise PolicyError(f"{SETTINGS}: not found")
        wanted = {
            SETTINGS: render_settings(current, deny),
            COPILOT: render_copilot(policy),
        }
        drift = 0
        for rel, text in wanted.items():
            path = os.path.join(args.root, rel)
            if _read(path) == text:
                continue
            drift = 1
            if args.check:
                print(
                    f"gen-policy: {rel} is out of date; run scripts/gen-policy.py",
                    file=sys.stderr,
                )
            else:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                with open(path, "w", encoding="utf-8") as handle:
                    handle.write(text)
                print(f"gen-policy: wrote {rel}")
    except (PolicyError, OSError, TypeError, AttributeError, ValueError) as err:
        print(f"gen-policy: {err}", file=sys.stderr)
        return 2
    return drift if args.check else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
